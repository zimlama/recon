def _make_runner():
    """Build a minimal JobRunner — the sweeper doesn't need modules or AI."""
    from app.orchestrator.job_runner import JobRunner

    return JobRunner(module_registry={}, ai_validator=None)  # type: ignore[arg-type]


@pytest.mark.asyncio
async def test_sweep_marks_old_validating_jobs_failed(jobs_only_db) -> None:
    """A job stuck in VALIDATING for >max_age_minutes is marked FAILED.

    Regression test for audit finding H2: a crash between VALIDATING and
    COMPLETED would otherwise leave the job orphaned forever.
    """
    db = jobs_only_db

    # Job stuck in VALIDATING for 60 minutes (older than 30-min cutoff).
    stuck = Job(
        id="stuck-job-1",
        target="stuck.example.com",
        status=JobStatus.VALIDATING,
        selected_modules=[],
        started_at=_now() - timedelta(minutes=60),
    )
    db.add(stuck)
    db.commit()

    runner = _make_runner()
    count = await runner.sweep_stuck_jobs(max_age_minutes=30)

    assert count == 1
    db.expire_all()
    refreshed = db.get(Job, "stuck-job-1")
    assert refreshed is not None
    assert refreshed.status == JobStatus.FAILED
    assert refreshed.error_message is not None
    assert "startup sweeper" in refreshed.error_message
    assert "VALIDATING" in refreshed.error_message


@pytest.mark.asyncio
async def test_sweep_skips_recent_validating_jobs(jobs_only_db) -> None:
    """Jobs in VALIDATING for LESS than max_age_minutes are NOT swept.

    A job that's been validating for 5 minutes is probably mid-flight on
    a slow machine — we must not kill it.
    """
    db = jobs_only_db

    recent = Job(
        id="recent-job",
        target="recent.example.com",
        status=JobStatus.VALIDATING,
        selected_modules=[],
        started_at=_now() - timedelta(minutes=5),
    )
    db.add(recent)
    db.commit()

    runner = _make_runner()
    count = await runner.sweep_stuck_jobs(max_age_minutes=30)

    assert count == 0
    db.expire_all()
    refreshed = db.get(Job, "recent-job")
    assert refreshed.status == JobStatus.VALIDATING


@pytest.mark.asyncio
async def test_sweep_skips_non_validating_jobs(jobs_only_db) -> None:
    """COMPLETED / FAILED / CANCELLED jobs are NOT touched.

    The sweeper exists to recover VALIDATING orphans only. Touching a
    COMPLETED job would silently break completed-history reporting.
    """
    db = jobs_only_db

    completed = Job(
        id="completed-job",
        target="done.example.com",
        status=JobStatus.COMPLETED,
        selected_modules=[],
        started_at=_now() - timedelta(hours=2),
        completed_at=_now() - timedelta(hours=1),
    )
    failed = Job(
        id="failed-job",
        target="broken.example.com",
        status=JobStatus.FAILED,
        selected_modules=[],
        started_at=_now() - timedelta(hours=2),
        error_message="Original failure",
    )
    pending = Job(
        id="pending-job",
        target="queued.example.com",
        status=JobStatus.PENDING,
        selected_modules=[],
        started_at=_now() - timedelta(hours=2),
    )
    db.add_all([completed, failed, pending])
    db.commit()

    runner = _make_runner()
    count = await runner.sweep_stuck_jobs(max_age_minutes=30)
    assert count == 0

    db.expire_all()
    assert db.get(Job, "completed-job").status == JobStatus.COMPLETED
    assert db.get(Job, "failed-job").status == JobStatus.FAILED
    assert db.get(Job, "failed-job").error_message == "Original failure"
    assert db.get(Job, "pending-job").status == JobStatus.PENDING


@pytest.mark.asyncio
async def test_sweep_returns_zero_when_nothing_to_sweep(jobs_only_db) -> None:
    """sweep_stuck_jobs returns 0 on an empty DB (not None, not -1)."""
    runner = _make_runner()
    count = await runner.sweep_stuck_jobs(max_age_minutes=30)
    assert count == 0


@pytest.mark.asyncio
async def test_sweep_counts_multiple_stuck_jobs(jobs_only_db) -> None:
    """sweep_stuck_jobs returns the count of all jobs swept in one pass."""
    db = jobs_only_db

    for i in range(3):
        db.add(
            Job(
                id=f"stuck-{i}",
                target=f"stuck{i}.example.com",
                status=JobStatus.VALIDATING,
                selected_modules=[],
                started_at=_now() - timedelta(minutes=45),
            )
        )
    db.commit()

    runner = _make_runner()
    count = await runner.sweep_stuck_jobs(max_age_minutes=30)
    assert count == 3
    db.expire_all()
    for i in range(3):
        assert db.get(Job, f"stuck-{i}").status == JobStatus.FAILED


@pytest.mark.asyncio
async def test_sweep_respects_custom_max_age(jobs_only_db) -> None:
    """A job older than a TIGHTER cutoff IS swept; a looser cutoff skips it."""
    db = jobs_only_db

    job = Job(
        id="boundary-job",
        target="boundary.example.com",
        status=JobStatus.VALIDATING,
        selected_modules=[],
        started_at=_now() - timedelta(minutes=20),
    )
    db.add(job)
    db.commit()

    runner = _make_runner()

    # 20 min job is OLDER than 10-min cutoff → swept.
    count = await runner.sweep_stuck_jobs(max_age_minutes=10)
    assert count == 1
    db.expire_all()
    assert db.get(Job, "boundary-job").status == JobStatus.FAILED