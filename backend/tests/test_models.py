def test_job_default_handoff_status_is_not_generated(jobs_only_db) -> None:
    """A new Job has handoff_status=NOT_GENERATED by default after flush.

    Regression test for audit finding H1: previously handoff generation
    state was conflated with module errors via error_message overloading.

    Note: SQLAlchemy `default=` is a column-level default applied at
    INSERT/flush time, not at Python object construction. We verify the
    default by reading the row back from the DB.
    """
    db = jobs_only_db
    job = Job(target="example.com", selected_modules=[])
    db.add(job)
    db.commit()
    db.refresh(job)
    assert job.handoff_status == HandoffStatus.NOT_GENERATED


def test_job_handoff_status_can_be_set_to_pending() -> None:
    """handoff_status accepts PENDING."""
    job = Job(target="example.com", selected_modules=[])
    job.handoff_status = HandoffStatus.PENDING
    assert job.handoff_status == HandoffStatus.PENDING


def test_job_handoff_status_can_be_set_to_generated() -> None:
    """handoff_status accepts GENERATED."""
    job = Job(target="example.com", selected_modules=[])
    job.handoff_status = HandoffStatus.GENERATED
    assert job.handoff_status == HandoffStatus.GENERATED


def test_job_handoff_status_can_be_set_to_failed() -> None:
    """handoff_status accepts FAILED."""
    job = Job(target="example.com", selected_modules=[])
    job.handoff_status = HandoffStatus.FAILED
    assert job.handoff_status == HandoffStatus.FAILED


def test_job_handoff_status_persists_round_trip(jobs_only_db) -> None:
    """handoff_status is persisted to the DB and read back."""
    db = jobs_only_db
    job = Job(
        target="example.com",
        selected_modules=[],
        handoff_status=HandoffStatus.GENERATED,
    )
    db.add(job)
    db.commit()

    db.expire_all()
    loaded = db.get(Job, job.id)
    assert loaded is not None
    assert loaded.handoff_status == HandoffStatus.GENERATED


def test_handoff_status_enum_values_are_strings() -> None:
    """HandoffStatus inherits from str — values serialize as plain strings."""
    assert HandoffStatus.NOT_GENERATED.value == "not_generated"
    assert HandoffStatus.PENDING.value == "pending"
    assert HandoffStatus.GENERATED.value == "generated"
    assert HandoffStatus.FAILED.value == "failed"


